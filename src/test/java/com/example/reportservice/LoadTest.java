    void testConcurrentGeneration() {
        int concurrentRequests = 1000;

        long start = System.currentTimeMillis();

        Flux.fromStream(IntStream.range(0, concurrentRequests).boxed())
                .flatMap(i -> generateReport()
                        .doOnNext(bytes ->
                                System.out.println("Request " + i + ": " + bytes.length + " bytes")
                        ), 1000)  // Concurrency level - 1000 parallel requests!
                .blockLast();

        long duration = System.currentTimeMillis() - start;
        System.out.println("Generated " + concurrentRequests +
                " reports in " + duration + "ms");
        System.out.println("Throughput: " +
                (concurrentRequests * 1000.0 / duration) + " reports/sec");
    }

